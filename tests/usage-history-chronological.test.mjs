import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import path from 'node:path';
import {once} from 'node:events';
import express from 'express';
const dir=mkdtempSync(path.join(process.env.TMPDIR,'usage-history-'));
Object.assign(process.env,{NODE_ENV:'test',DATABASE_URL:`sqlite:${path.join(dir,'db.sqlite')}`,ENCRYPTION_KEY:'a'.repeat(64),ADMIN_API_KEY:'x'.repeat(20),LOG_LEVEL:'error',LOG_PRETTY:'false'});
const {getDb,closeDatabase}=await import('../src/db/client.ts');
const {AccountRepository}=await import('../src/db/repositories/accounts.ts');
const {UsageLogRepository}=await import('../src/db/repositories/usage-logs.ts');
const {default:admin}=await import('../src/routes/admin.ts');
// The production client never creates a database; provision this test-owned fresh file.
await (await import('./helpers/fresh-db.mjs')).provisionFromEnv();
const db=getDb();db.prepare('INSERT INTO users (id,api_key_hash,name,email,tier) VALUES (?,?,?,?,?)').run('u','h','u','u@example.invalid','free');
const account=new AccountRepository().create({name:'test',provider:'openai',credentialType:'api_key',credentials:'fixture'});
const insert=db.prepare('INSERT INTO usage_logs(id,user_id,upstream_account_id,timestamp,model,provider,input_tokens,output_tokens,success,latency_ms) VALUES(?,?,?,?,?,?,0,0,1,0)');
for(const [id,t] of [['legacy','2030-02-28 23:00:00'],['iso','2030-02-28T01:00:00.000Z'],['tie-a','2030-02-28 12:00:00'],['tie-b','2030-02-28T12:00:00.000Z'],['invalid-a','2030-02-30T01:00:00.000Z'],['invalid-b','bad']]) insert.run(id,'u',account.id,t,'gpt-5','openai');
db.exec("CREATE TABLE siwc_accounts(id TEXT PRIMARY KEY,name TEXT NOT NULL); INSERT INTO siwc_accounts VALUES('siwc','fixture')");
db.prepare('INSERT INTO siwc_usage_logs(id,user_id,account_id,timestamp,model,provider,success,aborted,status,latency_ms) VALUES(?,?,?,?,?,?,1,0,200,0)').run('tie-b','u','siwc','2030-02-28T12:00:00.000Z','gpt-5','openai');
const app=express();app.use('/admin',admin);const server=app.listen(0,'127.0.0.1');await once(server,'listening');
after(async()=>{await new Promise(r=>server.close(r));closeDatabase();rmSync(dir,{recursive:true,force:true});});
test('admin and repository history sort canonical UTC, ties and invalid rows deterministically',async()=>{
 const url=`http://127.0.0.1:${server.address().port}/admin/users/u`;
 assert.equal((await fetch(url)).status,401);
 const r=await fetch(url,{headers:{authorization:`Bearer ${process.env.ADMIN_API_KEY}`}});assert.equal(r.status,200);
 const body=await r.json();const expected=['legacy','tie-b','tie-a','iso','invalid-b','invalid-a'];
 const mixed=['legacy','tie-b','tie-b','tie-a','iso','invalid-b','invalid-a'];
 assert.deepEqual(body.recentLogs.map(x=>x.id),mixed);
 const repo=new UsageLogRepository();
 const userPages=[0,2,4,6].flatMap(offset=>repo.findByUser('u',2,offset));
 assert.deepEqual(userPages.map(x=>x.id),mixed);
 assert.equal(new Set(userPages.map(x=>`${x.accountKind}:${x.id}`)).size,7);
 assert.deepEqual(userPages.slice(1,3).map(x=>x.accountKind),['upstream','siwc']);
 const accountPages=[0,2,4].flatMap(offset=>repo.findByAccount(account.id,2,offset));
 assert.deepEqual(accountPages.map(x=>x.id),expected);
 const accountResponse=await fetch(`http://127.0.0.1:${server.address().port}/admin/accounts/${account.id}`,{headers:{authorization:`Bearer ${process.env.ADMIN_API_KEY}`}});
 assert.equal(accountResponse.status,200);assert.deepEqual((await accountResponse.json()).recentLogs.map(x=>x.id),expected);
});
